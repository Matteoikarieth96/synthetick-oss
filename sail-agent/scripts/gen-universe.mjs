#!/usr/bin/env node
/**
 * Regenerate src/universe.ts from the SyntheTick Robinhood registry + live
 * GeckoTerminal Uniswap V3 pool discovery.
 *
 *   node scripts/gen-universe.mjs [--min-reserve 15000]
 *
 * Tradable = has a Uniswap V3 (canonical factory) pool against USDG with
 * reserve >= --min-reserve. WETH-paired tokens are excluded: the mandate is a
 * strict USDG hub (exactInputSingle only — no multi-hop path support in
 * SwapPermissionNoOracle).
 *
 * Pool reserves come from GeckoTerminal's API and are used only to filter and
 * sort here; they are not written to src/universe.ts.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const MIN_RESERVE = Number(process.argv.includes("--min-reserve")
  ? process.argv[process.argv.indexOf("--min-reserve") + 1]
  : 15000);

const REGISTRY_URL = "https://synthetick.org/v1/universe/robinhood";
const GT = "https://api.geckoterminal.com/api/v2/networks/robinhood";
const DEX_ID = "uniswap-v3-robinhood";
const OUT = fileURLToPath(new URL("../src/universe.ts", import.meta.url));

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function getJson(url, tries = 3) {
  for (let i = 0; i < tries; i++) {
    const res = await fetch(url, { headers: { accept: "application/json" } });
    if (res.ok) return res.json();
    if (res.status === 429) { await sleep(8000); continue; }
    throw new Error(`${url} -> HTTP ${res.status}`);
  }
  throw new Error(`${url} -> rate limited after ${tries} tries`);
}

const reg = await getJson(REGISTRY_URL);
const usdg = reg.core.find((c) => c.symbol === "USDG");
const weth = reg.core.find((c) => c.symbol === "WETH");

const rows = [];
for (const asset of reg.assets) {
  let d;
  try {
    d = await getJson(`${GT}/tokens/${asset.address}/pools`);
  } catch (e) {
    console.error(`  ${asset.symbol}: ${e.message} — skipped`);
    continue;
  }
  await sleep(2500);
  let best = null;
  for (const p of d.data ?? []) {
    if (p.relationships.dex.data.id !== DEX_ID) continue;
    const base = p.relationships.base_token.data.id.split("_").pop().toLowerCase();
    const quote = p.relationships.quote_token.data.id.split("_").pop().toLowerCase();
    const self = asset.address.toLowerCase();
    const other = base === self ? quote : quote === self ? base : null;
    if (other !== usdg.address.toLowerCase()) continue; // strict USDG hub
    const feeMatch = p.attributes.name.match(/(\d+(?:\.\d+)?)%$/);
    if (!feeMatch) continue;
    const reserve = Number(p.attributes.reserve_in_usd ?? 0);
    if (!best || reserve > best.reserveUsd) {
      best = {
        symbol: asset.symbol,
        name: asset.name,
        token: asset.address,
        decimals: asset.decimals,
        pool: p.attributes.address,
        feeTier: Math.round(Number(feeMatch[1]) * 10000),
        reserveUsd: Math.round(reserve),
      };
    }
  }
  if (best && best.reserveUsd >= MIN_RESERVE) {
    rows.push(best);
    console.error(`  ${best.symbol}: pool ${best.pool} fee=${best.feeTier} reserve=$${best.reserveUsd}`);
  }
}

rows.sort((a, b) => b.reserveUsd - a.reserveUsd);

// Emit on-chain facts only: the vendor reserve figure stays out of the output.
const emitted = rows.map(({ symbol, name, token, decimals, pool, feeTier }) => ({
  symbol, name, token, decimals, pool, feeTier,
}));

const ts = `// GENERATED by scripts/gen-universe.mjs — do not edit by hand.
// Source: ${REGISTRY_URL} + GeckoTerminal V3 pool discovery (${new Date().toISOString().slice(0, 10)}).
// Tradable = Uniswap V3 USDG pool with reserve >= $${MIN_RESERVE}.
import type { Address } from "@sail.money/sailor/sdk";

export interface TradableAsset {
  symbol: string;
  name: string;
  token: Address;
  decimals: number;
  pool: Address;      // the USDG/<token> V3 pool — also the mandate's reference pool
  feeTier: number;    // Uniswap V3 fee, hundredths of a bip (3000 = 0.30%)
}

export const CHAIN_ID = ${reg.chainId};
export const USDG: Address = "${usdg.address}";
export const USDG_DECIMALS = ${usdg.decimals};
export const WETH: Address = "${weth.address}";

// Canonical Uniswap V3 on Robinhood Chain (verified on-chain: pool.factory()
// matches, quoter.WETH9() matches the chain's WETH).
export const UNIV3_FACTORY: Address = "0x1f7d7550B1b028f7571E69A784071F0205FD2EfA";
export const SWAP_ROUTER_02: Address = "0xCaf681a66D020601342297493863E78C959E5cb2";
export const QUOTER_V2: Address = "0x33e885eD0Ec9bF04EcfB19341582aADCb4c8A9E7";

export const TRADABLE: TradableAsset[] = ${JSON.stringify(emitted, null, 2).replace(/"(0x[0-9a-fA-F]{40})"/g, '"$1" as Address')};

export const bySymbol = new Map(TRADABLE.map((t) => [t.symbol, t]));
export const byToken = new Map(TRADABLE.map((t) => [t.token.toLowerCase(), t]));
`;

writeFileSync(OUT, ts);
console.error(`wrote ${OUT} — ${emitted.length} tradable assets`);
